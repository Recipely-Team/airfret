// Generates PROJECT-MAP.md: a compact index of src/ so a reader (or an agent) learns the layout
// without listing directories. `check:structure` rule J fails while the map is stale.
//
//   node scripts/project-map.mjs        → rewrite PROJECT-MAP.md

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = 'src';

function walk(dir) {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? walk(p) : [p];
    });
}

/** Hash of every path under src/: changes whenever a file is added, moved or removed. */
export function mapFingerprint() {
  return createHash('sha256').update(walk(ROOT).filter((f) => !f.split(sep).includes('__tests__')).join('\n')).digest('hex').slice(0, 16);
}

/** First sentence of a file's head doc comment, if any. */
function summary(file) {
  if (!file.endsWith('.ts')) return '';
  const m = /\/\*\*\s*\n?\s*\*?\s*([^\n]*)/.exec(readFileSync(file, 'utf8'));
  return m ? m[1].replace(/\*\*/g, '').replace(/\s*\*\/$/, '').trim().slice(0, 110) : '';
}

function build() {
  const byDir = new Map();
  for (const f of walk(ROOT)) {
    if (f.split(sep).includes('__tests__')) continue;
    const dir = f.slice(0, f.lastIndexOf(sep));
    byDir.set(dir, [...(byDir.get(dir) ?? []), f]);
  }
  const out = [
    '# Project map',
    '',
    'Generated by `npm run map` — do not edit. One line per source file with its head comment.',
    'Layers and rules: `CLAUDE.md`, `architecture.md`.',
    '',
    `<!-- fingerprint: ${mapFingerprint()} -->`,
    '',
  ];
  for (const [dir, files] of byDir) {
    out.push(`## ${dir.split(sep).join('/')}/`, '');
    for (const f of files) {
      const s = summary(f);
      out.push(`- \`${f.slice(dir.length + 1)}\`${s ? ` — ${s}` : ''}`);
    }
    out.push('');
  }
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync('PROJECT-MAP.md', build());
  console.log('PROJECT-MAP.md written.');
}
