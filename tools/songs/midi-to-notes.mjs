// Converts a Standard MIDI File into Airfret's note notation, chords allowed:
//   node tools/songs/midi-to-notes.mjs <file.mid> [--transpose -12] [--grid 12] [--reference out.json]
//                                     [--module out.ts --name CONST --doc "what and where from"]
//
// Every onset becomes one token "PITCH[+PITCH…]:LENGTH" with the highest (melody) note first, so the
// lesson grades the tune and the guide plays the harmony under it. Gaps become rests (r:LENGTH).
// Onsets snap to 1/grid of a beat (12 keeps sixteenths and triplets exact); lengths that aren't exact
// decimals are written as fractions ("1/3"). Prints the score tempo and meter for the Song entry.
//
// `--reference` also writes the unquantised score — [beat, midi] per note — as the fixture the real-song
// tests compare the app's performance against. `--module` writes the notation as a TypeScript constant
// for `src/domain/lessons/catalog/pieces/`. Public-domain sources only (e.g. Mutopia Project).
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import { parseMidi } from './midi.mjs';

const NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
const args = process.argv.slice(2);
const opt = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const transpose = Number(opt('--transpose', 0));
const grid = Number(opt('--grid', 12));
const reference = opt('--reference', null);
const module = opt('--module', null);
const LINE = 110;

const { notes, tempos, meter } = parseMidi(readFileSync(args[0]));
const onsets = new Map();
for (const n of notes) {
  const slot = Math.round(n.beat * grid);
  onsets.set(slot, [...(onsets.get(slot) ?? []), n.midi + transpose]);
}
const slots = [...onsets.keys()].sort((a, b) => a - b);
const lastEnd = Math.round(Math.max(...notes.map((n) => n.beat + n.dur)) * grid);
const tokens = [];
if (slots[0] > 0) tokens.push(`r:${len(slots[0])}`);
slots.forEach((s, i) => {
  const next = slots[i + 1] ?? Math.max(lastEnd, s + 1);
  const pitches = [...new Set(onsets.get(s))].sort((x, y) => y - x).map(name);
  tokens.push(`${pitches.join('+')}:${len(next - s)}`);
});
console.log(tokens.join(' '));
if (module) writeModule(module, opt('--name', 'NOTES'), opt('--doc', basename(args[0])));
const all = notes.map((n) => n.midi + transpose);
const beatsPerBar = (meter.numerator * 4) / meter.denominator;
console.error(`${tokens.length} onsets, range ${name(Math.min(...all))}–${name(Math.max(...all))}, ${len(lastEnd)} beats`);
console.error(`tempo ${tempos.map((t) => `${round(t.bpm)} bpm @ beat ${round(t.beat)}`).join(', ')}; meter ${meter.numerator}/${meter.denominator} (${beatsPerBar} beats per bar)`);
if (tempos.length > 1) console.error('warning: the score changes tempo; the lesson plays at the first one');
if (reference) {
  const fixture = { source: basename(args[0]), bpm: round(tempos[0].bpm), transpose, notes: notes.map((n) => [round(n.beat), n.midi + transpose]) };
  writeFileSync(reference, `${JSON.stringify(fixture)}\n`);
  console.error(`reference written to ${reference}`);
}

/** The notation as `export const NAME = '…' + '…';`, wrapped so no line runs long. */
function writeModule(path, constName, doc) {
  const lines = [];
  let line = '';
  for (const t of tokens) {
    if (line && line.length + t.length + 1 > LINE) {
      lines.push(line.trimEnd());
      line = '';
    }
    line += `${t} `;
  }
  lines.push(line.trimEnd());
  const body = lines.map((l, i) => `  '${l}${i < lines.length - 1 ? ' ' : ''}'`).join(' +\n');
  writeFileSync(path, `/**\n${wrap(doc)}\n *\n * Generated by \`tools/songs/midi-to-notes.mjs\` — regenerate rather than edit.\n */\nexport const ${constName} =\n${body};\n`);
  console.error(`module written to ${path}`);
}

function wrap(text) {
  const out = [];
  let line = ' *';
  for (const w of text.split(' ')) {
    if (line.length + w.length + 1 > LINE) {
      out.push(line);
      line = ' *';
    }
    line += ` ${w}`;
  }
  return [...out, line].join('\n');
}

function name(midi) {
  return `${NAMES[midi % 12]}${Math.floor(midi / 12) - 1}`;
}

/** A length in grid steps, as the shortest exact text: "1", "0.75", "1/3". */
function len(steps) {
  const g = gcd(steps, grid);
  const [num, den] = [steps / g, grid / g];
  if (den === 1) return String(num);
  return [2, 4, 8].includes(den) ? String(num / den) : `${num}/${den}`;
}

function gcd(a, b) {
  return b === 0 ? a : gcd(b, a % b);
}

function round(x) {
  return Math.round(x * 10000) / 10000;
}
